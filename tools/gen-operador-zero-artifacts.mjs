#!/usr/bin/env node
// Vendor the ten served Operador Zero artifacts into the website bundle.
//
// The website Docker image is built from the `website/` directory ALONE (compose `context:
// .../website`, Dockerfile `COPY . ./`). The canonical artifact tree lives at
// `examples/operators/zero/`, OUTSIDE that context, so it is unavailable to `next build` and to the
// running container — a route handler that read it at runtime 500s in production (which is exactly
// how M2.12B found this). So the served payloads are vendored here, the same way the Rust engines are
// vendored as WASM under website/lib/wasm.
//
// `examples/operators/zero/` stays the ONE source of truth: this file is generated FROM it, and
// `make operator-zero-check` fails the build if the vendored copy drifts (it regenerates to a temp
// file and diffs). Run: `node tools/gen-operador-zero-artifacts.mjs` (also: `--check <tmp>` to emit
// to a path for the freshness guard).

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ZERO = join(ROOT, "examples", "operators", "zero");

// route → canonical file. MUST match ARTIFACT_ROUTES in website/lib/operadorZero.ts.
const ARTIFACTS = [
  [".well-known/banza/operator", "manifest/operator-zero.manifest.valid.json"],
  ["key-manifest", "keys/demo-key-manifest.json"],
  ["revocation-list", "keys/revocation-list.demo.json"],
  ["conformance/evidence", "conformance/conformance-pass.json"],
  ["federation/metadata", "federation/federation-manifest.demo.json"],
  ["evidence-bundle", "evidence-bundle/evidence-bundle.complete.json"],
  ["traces/full-e2e", "traces/full-e2e-trace.json"],
  ["ledger/demo", "ledger/demo-accounts.json"],
  ["payments/demo-qr", "payments/demo-qr-payment.json"],
  ["payments/demo-refund", "payments/demo-refund.json"],
  ["discovery", "discovery/discovery.json"],
  ["capabilities", "capabilities/capabilities.json"],
  [".well-known/banza/signed-protocol-metadata", "metadata/signed-metadata.json"],
  ["federation-metadata", "federation/federation-metadata.json"],
];

const data = {};
for (const [route, file] of ARTIFACTS) {
  // Parse then re-serialise so a syntactically broken canonical file fails HERE, not in the browser.
  data[route] = JSON.parse(readFileSync(join(ZERO, file), "utf8"));
}

// M2.14A — the versioned demo-validation state of the Operador Zero simulator, shown on
// zero.banza.network. It is NOT one of the ten served JSON endpoints (routing lists stay stable);
// it is a vendored constant the standalone lab renders. Source of truth is the same canonical tree.
const validationState = JSON.parse(
  readFileSync(join(ZERO, "status", "operator-zero-validation-state.json"), "utf8"),
);

const body = `// GENERATED by tools/gen-operador-zero-artifacts.mjs — DO NOT EDIT. RUST_WRAPPER_ONLY.
//
// The ten served Operador Zero artifacts, vendored from examples/operators/zero/ so the website
// Docker image (built from website/ alone) can serve them without a runtime filesystem read. The
// canonical source is examples/operators/zero/; \`make operator-zero-check\` fails if this drifts.
//
// RUST_WRAPPER_ONLY: this is inert DATA, not an engine. It carries no logic — but the embedded
// artifact JSON contains engine marker strings (e.g. the \`evidence_bundle\` artifact type and a
// \`fail-closed\` note), which the Rust-first guard scans for. The simulator's engine is Rust
// (operator-zero-core); this file only holds the JSON that engine validated.

export const ARTIFACT_DATA: Record<string, unknown> = ${JSON.stringify(data, null, 2)};

// M2.14A — versioned demo-validation state (rendered on zero.banza.network; not a served endpoint).
export const VALIDATION_STATE: Record<string, unknown> = ${JSON.stringify(validationState, null, 2)};
`;

const outArg = process.argv[3]; // when called as `--check <path>`
const out = process.argv[2] === "--check" && outArg
  ? outArg
  : join(ROOT, "website", "lib", "operadorZeroArtifacts.generated.ts");

writeFileSync(out, body);
if (process.argv[2] !== "--check") console.error(`wrote ${out} (${ARTIFACTS.length} artifacts)`);

pub fn repo_index_manifest() -> &'static str {
    REPO_INDEX_MANIFEST_JSON
}

/// The stable index hash from the manifest (used by the JS cache key so a changed index invalidates
/// every cached model answer). Returns "" if the manifest is unreadable.
pub fn repo_index_hash() -> &'static str {
    static H: OnceLock<String> = OnceLock::new();
    H.get_or_init(|| {
        serde_json::from_str::<serde_json::Value>(REPO_INDEX_MANIFEST_JSON)
            .ok()
            .and_then(|v| {
                v.get("index_hash")
                    .and_then(|x| x.as_str())
                    .map(String::from)
            })
            .unwrap_or_default()
    })
}


/// The entry keyword index: the candidate set for `retrieve_topk_ids`, generated by
/// `tools/gen-banzai-entries-index.mjs` from the subset of knowledge.js `ENTRIES` explicitly marked
/// `lexicalCandidate: true` (id + keywords).
///
/// It is a CURATED ALLOWLIST, not a projection of every entry, and membership is NOT `critical`. Most
/// critical entries are deliberately absent and are resolved by the subject, concept, glossary and
/// deterministic paths instead. A reader who counts 27 rows next to 163 entries and concludes the file
/// is stale would be wrong — and the previous wording, "generated from `ENTRIES`", invited exactly that
/// conclusion. Adding an entry here changes which questions this keyword mechanism can win, so it is a
/// deliberate decision recorded at the source, one entry at a time.
const ENTRIES_JSON: &str = include_str!("entries-index.json");

#[derive(Deserialize)]
struct Entry {
    id: String,
    keywords: Vec<String>,
    /// Whether this entry is STABLE KNOWLEDGE the engine may state without a model.
    ///
    /// Declared on the canonical entry and derived into the index. It replaces an inference from the id
    /// prefix — a `def-` name used to mean "settle this model-free", which put semantics in a naming
    /// convention where nobody could see it and where the two cases that matter are inexpressible: a
    /// definition that should NOT be settled, and a settled fact whose id is not a definition.
    ///
    /// Defaults to false so an index generated before this field existed cannot silently promote anything.
    #[serde(default)]
    deterministic: bool,
}

/// Surface forms the RESOLVER recognises: keywords of indexed entries, words of critical-subject
/// aliases, and canonical profile identifiers.
///
/// Typo recovery consults this so it cannot "repair" a word that is already valid vocabulary. Measured
/// before it existed: "What are the BANZA profiles?" had `profiles` rewritten to `profile` as a
/// high-confidence correction, because the fuzzy vocabulary happened to carry the singular and not the
/// plural — and the router only ever sees the corrected form, so a legitimate English plural was
/// normalised out of its own alias while the Portuguese twin matched.
///
/// Deliberately NOT "every word in the documentation": that would freeze the corpus and disable recovery
/// wherever a misspelling coincides with prose. Only vocabulary a resolver actually matches on.
/// Technical terms the engine knows that are too short for the fuzzy vocabulary's five-character floor.
///
/// See the comment at the use site in `registered_surface_forms`. Every member must be resolvable by
/// the glossary on its own — enforced by `tests/known_word_is_not_a_typo.rs`.
const SHORT_DECLARED_TERMS: &[&str] = &[
    "rust", "wasm", "adr", "rfc", "bcj", "qr", "kyc", "kyb", "psp",
];

/// The short declared terms, for the guard that pins each of them to a word the glossary resolves.
pub fn short_declared_terms() -> &'static [&'static str] {
    SHORT_DECLARED_TERMS
}

fn registered_surface_forms() -> &'static std::collections::HashSet<String> {
    static V: OnceLock<std::collections::HashSet<String>> = OnceLock::new();
    V.get_or_init(|| {
        let mut set = std::collections::HashSet::new();
        for e in entries() {
            for k in &e.keywords {
                for w in normalize(k).split(' ') {
                    if w.chars().count() > 2 {
                        set.insert(w.to_string());
                    }
                }
            }
        }
        for w in crate::glossary::critical_subject_words() {
            let n = normalize(w);
            if n.chars().count() > 2 {
                set.insert(n);
            }
        }
        // Declared technical terms SHORTER than the fuzzy vocabulary's floor.
        //
        // Two different questions were being answered by one set: which words a typo may be corrected
        // TO, and which words are KNOWN and must never be corrected FROM. `fuzzy::vocabulary` answers
        // the first, and admits only tokens of five characters or more — a sensible rule for correction
        // targets, which then silently decided that every shorter declared term was an unknown word.
        //
        // `rust` is four characters. It is a concept this engine answers (`def-rust`), and ADR-038 makes
        // it the language of every official BANZA engine. Recovery rewrote it to `trust` — one edit
        // away, five characters, in the target set — at high confidence, in every phrasing, before any
        // router saw the question. Production then answered "não é necessário usar trust para
        // implementar BANZA".
        //
        // This list is deliberately NOT the concept-alias table. That table is matched by SUBSTRING, so
        // an alias `rust` there matches inside `trust` and sends every trust question to ADR-038 —
        // measured, and caught by the golden-answer guard before it shipped. These terms are for
        // known-word protection only: never a correction target, never a concept alias.
        //
        // `short_declared_terms_are_resolvable` pins every member to something the glossary actually
        // resolves, so this cannot drift into a list of words the engine does not know.
        for w in SHORT_DECLARED_TERMS {
            set.insert(normalize(w));
        }
        for p in crate::canonical_profiles::CANONICAL_PROFILES.iter() {
            set.insert(normalize(p.level));
        }
        set
    })
}

/// Whole keywords of indexed entries — COMPLETE surfaces, not the words they are made of.
///
/// `registered_surface_forms()` below splits keywords into words, which is right for typo recovery and
/// wrong for deciding whether a turn names a subject. The two are kept apart deliberately.
pub(crate) fn entry_keyword_surfaces() -> &'static std::collections::HashSet<String> {
    static K: OnceLock<std::collections::HashSet<String>> = OnceLock::new();
    K.get_or_init(|| {
        entries()
            .iter()
            .flat_map(|e| e.keywords.iter())
            .map(|k| normalize(k))
            .collect()
    })
}

/// True when `tok` is a surface form the resolver already recognises, so recovery must leave it alone.
pub fn is_registered_surface_form(tok: &str) -> bool {
    registered_surface_forms().contains(tok)
}

/// Whether the entry with this id is declared stable knowledge answerable without a model.
pub fn entry_is_deterministic(entry_id: &str) -> bool {
    entries()
        .iter()
        .any(|e| e.id == entry_id && e.deterministic)
}

fn entries() -> &'static [Entry] {
    static E: OnceLock<Vec<Entry>> = OnceLock::new();
    E.get_or_init(|| serde_json::from_str(ENTRIES_JSON).expect("entries-index.json"))
}

// ── M2.9A (ADR-036) documentary index — real protocol-doc chunks generated by the build-time
// banzai-doc-indexer. Used ONLY to ENRICH the grounded Qwen context with real doc excerpts; it never
// changes routing and the curated entries remain the primary grounding/fallback. ──

/// The documentary index (generated by `banzai-doc-indexer`; excludes all secrets/keys/infra).
const DOC_INDEX_JSON: &str = include_str!("doc-index.json");

#[derive(Deserialize)]
pub struct DocChunk {
    pub path: String,
    pub title: String,
    pub section: String,
    pub anchor: String,
    pub source_type: String,
    #[serde(default)]
    pub tags: Vec<String>,
    pub chunk: String,
    #[serde(default)]
    pub operator_facing_flag: bool,
}

pub fn doc_chunks() -> &'static [DocChunk] {
    static D: OnceLock<Vec<DocChunk>> = OnceLock::new();
    D.get_or_init(|| serde_json::from_str(DOC_INDEX_JSON).unwrap_or_default())
}

/// Score a documentary chunk against the normalized query terms: count distinct query terms (len>2)
/// present in the chunk's normalized (title+section+tags+text), + a small operator-facing boost when
/// the query itself is operator-oriented. Deterministic; no LLM.
fn score_doc_chunk(terms: &[&str], operator_query: bool, c: &DocChunk) -> i64 {
    let hay = normalize(&format!(
        "{} {} {} {}",
        c.title,
        c.section,
        c.tags.join(" "),
        c.chunk
    ));
    let mut score = 0i64;
    for t in terms {
        if t.len() > 2 && hay.contains(t) {
            score += 1;
        }
    }
    if operator_query && c.operator_facing_flag && score > 0 {
        score += 1;
    }
    score
}

/// Retrieve the top-k documentary chunks for a query (score ≥ 3), best first, stable for ties.
pub fn retrieve_doc_chunks(query: &str, k: usize) -> Vec<&'static DocChunk> {
    let nq = normalize(query);
    if nq.is_empty() {
        return vec![];
    }
    let terms: Vec<&str> = nq.split(' ').filter(|w| w.len() > 2).collect();
    if terms.is_empty() {
        return vec![];
    }
    let operator_query = terms.iter().any(|t| {
        matches!(
            *t,
            "operador"
                | "operator"
                | "onboarding"
                | "federar"
                | "federacao"
                | "conformidade"
                | "conformance"
                | "manifest"
                | "manifesto"
                | "evidencia"
                | "evidence"
                | "trust"
                | "implementar"
                | "comeco"
                | "comecar"
        )
    });
    let mut kept: Vec<(usize, i64, &'static DocChunk)> = doc_chunks()
        .iter()
        .enumerate()
        .map(|(i, c)| (i, score_doc_chunk(&terms, operator_query, c), c))
        .filter(|x| x.1 >= 3)
        .collect();
    kept.sort_by_key(|x| (std::cmp::Reverse(x.1), x.0));
    kept.into_iter().take(k.max(1)).map(|x| x.2).collect()
}


/// The documentary index (generated by `banzai-doc-indexer`; excludes all secrets/keys/infra).
const DOC_INDEX_JSON: &str = include_str!("doc-index.json");

#[derive(Deserialize)]
pub struct DocChunk {
    pub path: String,
    pub title: String,
    pub section: String,
    pub anchor: String,
    pub source_type: String,
    #[serde(default)]
    pub tags: Vec<String>,
    pub chunk: String,
    #[serde(default)]
    pub operator_facing_flag: bool,
}

pub fn doc_chunks() -> &'static [DocChunk] {
    static D: OnceLock<Vec<DocChunk>> = OnceLock::new();
    D.get_or_init(|| serde_json::from_str(DOC_INDEX_JSON).unwrap_or_default())
}

/// Score a documentary chunk against the normalized query terms: count distinct query terms (len>2)
/// present in the chunk's normalized (title+section+tags+text), + a small operator-facing boost when
/// the query itself is operator-oriented. Deterministic; no LLM.
fn score_doc_chunk(terms: &[&str], operator_query: bool, c: &DocChunk) -> i64 {
    let hay = normalize(&format!(
        "{} {} {} {}",
        c.title,
        c.section,
        c.tags.join(" "),
        c.chunk
    ));
    let mut score = 0i64;
    for t in terms {
        if t.len() > 2 && hay.contains(t) {
            score += 1;
        }
    }
    if operator_query && c.operator_facing_flag && score > 0 {
        score += 1;
    }
    score
}

/// Retrieve the top-k documentary chunks for a query (score ≥ 3), best first, stable for ties.
pub fn retrieve_doc_chunks(query: &str, k: usize) -> Vec<&'static DocChunk> {
    let nq = normalize(query);
    if nq.is_empty() {
        return vec![];
    }
    let terms: Vec<&str> = nq.split(' ').filter(|w| w.len() > 2).collect();
    if terms.is_empty() {
        return vec![];
    }
    let operator_query = terms.iter().any(|t| {
        matches!(
            *t,
            "operador"
                | "operator"
                | "onboarding"
                | "federar"
                | "federacao"
                | "conformidade"
                | "conformance"
                | "manifest"
                | "manifesto"
                | "evidencia"
                | "evidence"
                | "trust"
                | "implementar"
                | "comeco"
                | "comecar"
        )
    });
    let mut kept: Vec<(usize, i64, &'static DocChunk)> = doc_chunks()
        .iter()
        .enumerate()
        .map(|(i, c)| (i, score_doc_chunk(&terms, operator_query, c), c))
        .filter(|x| x.1 >= 3)
        .collect();
    kept.sort_by_key(|x| (std::cmp::Reverse(x.1), x.0));
    kept.into_iter().take(k.max(1)).map(|x| x.2).collect()
}

